def get_tip(waste_type: WasteType) -> str:
    """
    Возвращает случайный эко-совет для данного типа отходов.

    Args:
        waste_type: Тип отходов.

    Returns:
        Строка с советом или фактом об экологии.
    """
    tips = ECO_TIPS.get(waste_type, ECO_TIPS[WasteType.MIXED])
    return random.choice(tips)


def get_all_tips(waste_type: WasteType) -> list[str]:
    """Возвращает все советы для данного типа отходов."""
    return list(ECO_TIPS.get(waste_type, ECO_TIPS[WasteType.MIXED]))
